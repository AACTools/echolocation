namespace echo {

uint8_t bootKeyToHidUsage(uint8_t boot_key) {
  static const uint8_t kTable[] = {
      0x00, 0x29, 0x1E, 0x1F, 0x20, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27,
      0x2D, 0x2E, 0x2A, 0x2B, 0x14, 0x1A, 0x08, 0x15, 0x17, 0x1C, 0x18, 0x0C,
      0x12, 0x13, 0x2F, 0x30, 0x28, 0xE0, 0xE1, 0xE2, 0xE3, 0x04, 0x16, 0x07,
      0x09, 0x0A, 0x0B, 0x0D, 0x0E, 0x0F, 0x33, 0x34, 0x10, 0x11, 0x36, 0x37,
      0x38, 0x05, 0x19, 0x1B, 0x06, 0x1D, 0x2C, 0x39, 0x3A, 0x3B, 0x3C, 0x3D,
      0x3E, 0x3F, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x68, 0x69, 0x6A, 0x6B,
      0x6C, 0x6D, 0x6E, 0x6F, 0x70, 0x71, 0x72, 0x73, 0x74, 0x54, 0x55, 0x56,
      0x57, 0x58, 0x59, 0x5A, 0x5B, 0x5C, 0x5D, 0x5E, 0x5F, 0x60, 0x61, 0x62,
      0x63, 0xE4, 0xE5, 0xE6, 0xE7};
  if (boot_key < sizeof(kTable)) {
    return kTable[boot_key];
  }
  return 0;
}

uint8_t bootModifierToHidUsage(uint8_t modifier_bit_mask) {
  switch (modifier_bit_mask) {
    case 0x01:
      return kLeftControl;
    case 0x02:
      return kLeftShift;
    case 0x04:
      return kLeftAlt;
    case 0x08:
      return kLeftGui;
    case 0x10:
      return kRightControl;
    case 0x20:
      return kRightShift;
    case 0x40:
      return kRightAlt;
    case 0x80:
      return kRightGui;
    default:
      return 0;
  }
}

}  // namespace echo
